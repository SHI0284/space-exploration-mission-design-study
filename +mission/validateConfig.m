function c = validateConfig(c)
spec = {'durationDays',0.05,14;'stepSeconds',1,120; ...
    'altitudeKm',200,2000;'inclinationDeg',0,180; ...
    'satellites',1,24;'planes',1,24;'raanDeg',0,360; ...
    'phaseDeg',0,360;'fovDeg',1,160;'minElevationDeg',0,89};
for k=1:size(spec,1)
    key=spec{k,1}; v=c.(key);
    assert(isnumeric(v)&&isscalar(v)&&isfinite(v)&&v>=spec{k,2}&&v<=spec{k,3}, ...
        'mission:Input','%s must be between %g and %g.',key,spec{k,2},spec{k,3});
end
assert(c.satellites==fix(c.satellites)&&c.planes==fix(c.planes)&& ...
    c.planes<=c.satellites&&mod(c.satellites,c.planes)==0, ...
    'mission:Input','Satellite count must be divisible by plane count.');
assert(any(strcmp(c.model,{'Two-body','J2 secular'})),'mission:Input','Unknown orbit model.');
epoch=datetime(c.epochUTC,'InputFormat','yyyy-MM-dd HH:mm:ss','TimeZone','UTC');
assert(isscalar(epoch)&&~isnat(epoch),'mission:Input','Invalid UTC epoch.');
assert(strlength(string(c.name))>0,'mission:Input','Enter a scenario name.');
for field={'targets','stations'}
    T=c.(field{1});
    assert(istable(T)&&height(T)>=1&&height(T)<=30&& ...
        all(ismember({'Name','LatitudeDeg','LongitudeDeg'},T.Properties.VariableNames)), ...
        'mission:Input','Provide 1 to 30 locations in each table.');
    assert(isnumeric(T.LatitudeDeg)&&isnumeric(T.LongitudeDeg)&& ...
        all(isfinite(T.LatitudeDeg)&abs(T.LatitudeDeg)<=90)& ...
        all(isfinite(T.LongitudeDeg)&abs(T.LongitudeDeg)<=180), ...
        'mission:Input','Latitude/longitude must be finite and in range.');
    assert(all(strlength(strtrim(string(T.Name)))>0)&& ...
        numel(unique(string(T.Name)))==height(T),'mission:Input','Location names must be nonempty and unique.');
end
n=ceil(c.durationDays*86400/c.stepSeconds)+1;
assert(n*c.satellites*(height(c.targets)+height(c.stations))<=3e7, ...
    'mission:Input','Scenario too large. Increase the time step or reduce the duration / locations.');
end
